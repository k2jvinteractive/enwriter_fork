const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadNovel: () => ipcRenderer.invoke('novel:load'),
  writeIndex: (index) => ipcRenderer.invoke('index:write', index),
  readChapter: (id) => ipcRenderer.invoke('chapter:read', id),
  writeChapter: (id, html) => ipcRenderer.invoke('chapter:write', id, html),
  createChapter: () => ipcRenderer.invoke('chapter:create'),
  deleteChapter: (id) => ipcRenderer.invoke('chapter:delete', id),
  getLibrary: () => ipcRenderer.invoke('library:get'),
  writeLibrary: (lib) => ipcRenderer.invoke('library:write', lib),
  createBook: (title) => ipcRenderer.invoke('book:create', title),
  openBook: (id) => ipcRenderer.invoke('book:open', id),
  closeBook: () => ipcRenderer.invoke('book:close'),
  renameBook: (id, title) => ipcRenderer.invoke('book:rename', id, title),
  deleteBook: (id) => ipcRenderer.invoke('book:delete', id),
  getCover: (id) => ipcRenderer.invoke('book:cover-get', id),
  setCover: (id, dataUrl) => ipcRenderer.invoke('book:cover-set', id, dataUrl),
  revealBook: (id) => ipcRenderer.invoke('book:reveal', id),
  chooseLibraryFolder: () => ipcRenderer.invoke('library:choose-folder'),
  inspectLibraryFolder: () => ipcRenderer.invoke('library:inspect-folder'),
  applyLibraryFolder: (mode) => ipcRenderer.invoke('library:apply-folder', mode),
  libraryInfo: () => ipcRenderer.invoke('library:info'),
  revealLibrary: () => ipcRenderer.invoke('library:reveal'),
  settingsSync: () => ipcRenderer.sendSync('settings:get-sync'),
  setZoom: (factor) => { if (typeof factor === 'number' && factor >= 0.5 && factor <= 2) webFrame.setZoomFactor(factor); },
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSetting: (key, value) => ipcRenderer.invoke('settings:set', key, value),
  snapshotCreate: (opts) => ipcRenderer.invoke('snapshot:create', opts),
  snapshotList: () => ipcRenderer.invoke('snapshot:list'),
  snapshotRestore: (id) => ipcRenderer.invoke('snapshot:restore', id),
  snapshotRename: (id, label) => ipcRenderer.invoke('snapshot:rename', id, label),
  snapshotRemove: (id) => ipcRenderer.invoke('snapshot:remove', id),
  snapshotRestoreRemoved: (id) => ipcRenderer.invoke('snapshot:restore-removed', id),
  snapshotOutline: (id) => ipcRenderer.invoke('snapshot:outline', id),
  onSpellContext: (cb) => ipcRenderer.on('spell:context', (_e, d) => cb(d)),
  spellReplace: (text) => ipcRenderer.invoke('spell:replace', text),
  spellInfo: () => ipcRenderer.invoke('spell:info'),
  spellSetLanguage: (id) => ipcRenderer.invoke('spell:set-language', id),
  onSpellDownload: (cb) => ipcRenderer.on('spell:download', (_e, d) => cb(d)),
  onThemeUpdated: (cb) => ipcRenderer.on('theme:updated', (_e, t) => cb(t)),
  onBeforeClose: (cb) => ipcRenderer.on('before-close', () => cb()),
  closeReady: () => ipcRenderer.send('close-ready')
});
